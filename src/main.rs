/// Logs a timestamped line to %APPDATA%\Sentinelle\sentinelle.log + stderr.
pub fn logln(msg: &str) {
    let ts = unsafe {
        let st = windows::Win32::System::SystemInformation::GetLocalTime();
        format!("{:02}:{:02}:{:02}", st.wHour, st.wMinute, st.wSecond)
    };
    let line = format!("[{ts}] {msg}");
    eprintln!("{line}");
    if let Ok(dir) = config::config_dir() {
        let _ = std::fs::create_dir_all(&dir);
        if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(dir.join("sentinelle.log")) {
            let _ = writeln!(f, "{line}");
        }
    }
}

fn prompt_password(confirm: bool) -> Result<String> {
    if let Ok(p) = std::env::var("SENTINELLE_PASSWORD") {
        if !p.is_empty() {
            return Ok(p);
        }
    }
    let pass = rpassword::prompt_password("Password: ")?;
    if pass.is_empty() {
        bail!("empty password rejected");
    }
    if confirm {
        let again = rpassword::prompt_password("Confirm password: ")?;
        if pass != again {
            bail!("passwords do not match");
        }
    }
    Ok(pass)
}

// ------------------------------------------------------------------- init
fn cmd_init() -> Result<()> {
    let mut cfg = Config::load()?;
    if cfg.is_initialized() {
        println!("Already initialized. The master password is already set.");
        return Ok(());
    }
    println!("Set Sentinelle's master password.");
    println!("WARNING: it protects ALL your folders. If you forget it, the data is unrecoverable.");
    let mut password = prompt_password(true)?;
    let salt = crypto::random_bytes::<16>();
    let key = crypto::derive_key(password.as_bytes(), &salt)?;
    password.zeroize();
    let (vnonce, v) = crypto::make_verifier(&key)?;
    cfg.salt = B64.encode(salt);
    cfg.verifier_nonce = B64.encode(vnonce);
    cfg.verifier = B64.encode(v);
    cfg.save()?;
    println!("Master password set. Run 'sentinelle scan' then 'sentinelle guard'.");
    Ok(())
}

// ------------------------------------------------------------------- scan
fn cmd_scan() -> Result<()> {
    let mut cfg = Config::load()?;
    let found = catalog::detect();
    println!("Detecting sensitive folders...\n");

    let mut known: std::collections::HashSet<String> =
        cfg.folders.iter().map(|f| f.path.to_lowercase()).collect();
    let mut added = 0usize;
    let mut current = String::new();
    for f in &found {
        if f.category != current {
            current = f.category.clone();
            println!("  [{}]", current);
        }
        let key = f.path.to_string_lossy().to_lowercase();
        let marker = if known.contains(&key) { "already tracked" } else { "NEW" };
        println!("    • {:<22} {}  ({})", f.label, f.path.display(), marker);
        if !known.contains(&key) {
            known.insert(key);
            cfg.folders.push(FolderEntry {
                path: f.path.to_string_lossy().to_string(),
                category: f.category.clone(),
                processes: f.processes.clone(),
            });
            added += 1;
        }
    }
    cfg.save()?;
    write_folders_txt(&cfg)?;
    println!("\n{} folder(s) detected, {} new one(s) added.", found.len(), added);
    println!("   Total tracked: {} folder(s).", cfg.folders.len());
    println!("   Readable list: folders.txt");
    if !cfg.is_initialized() {
        println!("\nNext step: 'sentinelle init' to set the master password.");
    }
    Ok(())
}

fn write_folders_txt(cfg: &Config) -> Result<()> {
    let mut out = String::from("# Folders tracked by Sentinelle (generated by 'scan').\n# Informational, editable. The real config is in %APPDATA%\\Sentinelle\\config.json\n\n");
    let mut current = String::new();
    for f in &cfg.folders {
        if f.category != current {
            current = f.category.clone();
            out.push_str(&format!("# --- {} ---\n", current));
        }
        out.push_str(&f.path);
        out.push('\n');
    }
    std::fs::write("folders.txt", out).context("writing folders.txt")?;
    Ok(())
}

// ------------------------------------------------------------------- list
fn cmd_list() -> Result<()> {
    let cfg = Config::load()?;
    println!("Master password: {}", if cfg.is_initialized() { "set" } else { "NOT set (run 'init')" });
    println!("Agent settings: screen-lock={}  idle={}({}min)  shutdown={}  unlock-on-return={}",
        cfg.lock_on_session_lock, cfg.lock_on_idle, cfg.idle_minutes, cfg.lock_on_shutdown, cfg.auto_unlock_on_resume);
    println!("\n{} folder(s) tracked:", cfg.folders.len());
    let mut current = String::new();
    for f in &cfg.folders {
        if f.category != current {
            current = f.category.clone();
            println!("  [{}]", current);
        }
        let dir = Path::new(&f.path);
        let state = if !dir.exists() {
            "not found"
        } else if vault::is_locked(dir) {
            "locked"
        } else {
            "cleartext"
        };
        println!("    {:<12} {}", state, f.path);
    }
    Ok(())
}

// ------------------------------------------------------- manual lock/unlock/status
fn cmd_lock(dir: &Path) -> Result<()> {
    if vault::is_locked(dir) {
        bail!("already locked. Use 'unlock'.");
    }
    let cfg = Config::load()?;
    // If the master password is set, use it (consistent with the agent):
    // any folder locked here becomes unlockable by the agent and vice versa.
    let (salt_b64, vnonce_b64, v_b64, key) = if cfg.is_initialized() {
        let mut password = prompt_password(false)?;
        let key = crypto::derive_key(password.as_bytes(), &B64.decode(&cfg.salt)?)?;
        password.zeroize();
        if !crypto::check_verifier(&key, &B64.decode(&cfg.verifier_nonce)?, &B64.decode(&cfg.verifier)?) {
            bail!("wrong master password");
        }
        (cfg.salt.clone(), cfg.verifier_nonce.clone(), cfg.verifier.clone(), key)
    } else {
        // no master password: standalone folder with its own salt
        let mut password = prompt_password(true)?;
        let salt = crypto::random_bytes::<16>();
        let key = crypto::derive_key(password.as_bytes(), &salt)?;
        password.zeroize();
        let (vnonce, v) = crypto::make_verifier(&key)?;
        (B64.encode(salt), B64.encode(vnonce), B64.encode(v), key)
    };
    let n = vault::lock_with_key(dir, &key, &salt_b64, &vnonce_b64, &v_b64)?;
    println!("Folder locked: {} file(s) encrypted.", n);
    Ok(())
}

fn cmd_unlock(dir: &Path) -> Result<()> {
    let salt = vault::salt_of(dir)?.ok_or_else(|| anyhow::anyhow!("this folder is not locked"))?;
    let mut password = prompt_password(false)?;
    let key = crypto::derive_key(password.as_bytes(), &B64.decode(&salt)?)?;
    password.zeroize();
    let n = vault::unlock_with_key(dir, &key)?;
    println!("Folder unlocked: {} file(s) restored.", n);
    Ok(())
}

fn cmd_status(dir: &Path) -> Result<()> {
    if vault::is_locked(dir) {
        println!("LOCKED - {} file(s) encrypted.", vault::count_encrypted(dir));
    } else {
        println!("Unlocked (cleartext).");
    }
    Ok(())
}

fn usage() {
    eprintln!(
        "Sentinelle — protects your sensitive data from stealers.\n\n\
         Getting started:\n  \
         sentinelle scan                 detect sensitive folders\n  \
         sentinelle init                 set the master password\n  \
         sentinelle guard                run the agent (auto-lock when you step away)\n\n\
         Others:\n  \
         sentinelle list                 list tracked folders and their state\n  \
         sentinelle lock|unlock|status <folder>   manual operation"
    );
}

/// Windowless background launch (double-click or the "guard" command): sets things up on
/// first run (silent detection + a password dialog), then watches with no visible window.
fn run_background() -> Result<()> {
    let mut cfg = Config::load()?;

    // first run: detect sensitive folders (silent)
    if cfg.folders.is_empty() {
        for f in &catalog::detect() {
            cfg.folders.push(FolderEntry {
                path: f.path.to_string_lossy().to_string(),
                category: f.category.clone(),
                processes: f.processes.clone(),
            });
        }
        cfg.save()?;
    }
    if cfg.folders.is_empty() {
        ui::message("No sensitive folder found to protect.", true);
        return Ok(());
    }

    // ensure a master password, then obtain it for this session
    let password = if cfg.is_initialized() {
        loop {
            let Some(p) = ui::password_dialog("Enter your Sentinelle master password:") else {
                return Ok(());
            };
            let key = crypto::derive_key(p.as_bytes(), &B64.decode(&cfg.salt)?)?;
            if crypto::check_verifier(&key, &B64.decode(&cfg.verifier_nonce)?, &B64.decode(&cfg.verifier)?) {
                break p;
            }
            ui::message("Wrong password.", true);
        }
    } else {
        loop {
            let Some(p1) = ui::password_dialog("Create your master password (do NOT forget it):") else {
                return Ok(());
            };
            if p1.is_empty() {
                ui::message("Empty password rejected.", true);
                continue;
            }
            let Some(p2) = ui::password_dialog("Confirm your master password:") else {
                return Ok(());
            };
            if p1 != p2 {
                ui::message("Passwords do not match.", true);
                continue;
            }
            let salt = crypto::random_bytes::<16>();
            let key = crypto::derive_key(p1.as_bytes(), &salt)?;
            let (vn, v) = crypto::make_verifier(&key)?;
            cfg.salt = B64.encode(salt);
            cfg.verifier_nonce = B64.encode(vn);
            cfg.verifier = B64.encode(v);
            cfg.save()?;
            break p1;
        }
    };

    // runs with no visible window (nothing in the taskbar)
    guard::run(cfg, password)
}

fn main() {
    let args: Vec<String> = std::env::args().collect();

    // Double-click (no arg) or "guard": windowless background app.
    if args.len() < 2 || args[1] == "guard" {
        if let Err(e) = run_background() {
            ui::message(&format!("Error: {e:#}"), true);
            std::process::exit(1);
        }
        return;
    }

    // CLI commands: attach to the parent console so output shows when run from a terminal.
    unsafe {
        let _ = windows::Win32::System::Console::AttachConsole(
            windows::Win32::System::Console::ATTACH_PARENT_PROCESS,
        );
    }
    let need_dir = |a: &[String]| -> Result<PathBuf> {
        a.get(2).map(PathBuf::from).ok_or_else(|| anyhow::anyhow!("missing folder path"))
    };
    let res = match args[1].as_str() {
        "scan" => cmd_scan(),
        "init" => cmd_init(),
        "list" => cmd_list(),
        "lock" => need_dir(&args).and_then(|d| cmd_lock(&d)),
        "unlock" => need_dir(&args).and_then(|d| cmd_unlock(&d)),
        "status" => need_dir(&args).and_then(|d| cmd_status(&d)),
        other => {
            eprintln!("Unknown command: {other}\n");
            usage();
            std::process::exit(2);
        }
    };
    if let Err(e) = res {
        eprintln!("Error: {e:#}");
        std::process::exit(1);
    }
}
