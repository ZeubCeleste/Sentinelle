//! Sentinelle — protects your sensitive data from stealers by encrypting your folders.
//!
//! Commands:
//!   sentinelle scan                 auto-detect sensitive folders
//!   sentinelle init                 set the master password
//!   sentinelle list                 show tracked folders and their state
//!   sentinelle guard                run the agent (visible window, auto-lock)
//!   sentinelle lock|unlock|status <folder>   manual operation on a folder
//!
//! Double-clicking the exe (no argument) runs the background watcher, setting things
//! up (detection + password) on first launch.

mod catalog;
